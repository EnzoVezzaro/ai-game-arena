export type IconName = keyof typeof REGISTRY;

export interface IconProps extends Omit<LucideProps, 'name'> {
  name: IconName | string;
  size?: number;
  strokeWidth?: number;
  className?: string;
  style?: CSSProperties;
}

/** Lucide icon wrapper — accepts a string icon name and falls back to Circle. */
export function Icon({ name, size = 16, strokeWidth = 2, className, style, ...rest }: IconProps) {
  const Cmp = (REGISTRY as Record<string, typeof Circle>)[name] ?? Circle;
  return (
    <Cmp className={className} size={size} strokeWidth={strokeWidth} style={style} {...rest} />
  );
}

export default Icon;
